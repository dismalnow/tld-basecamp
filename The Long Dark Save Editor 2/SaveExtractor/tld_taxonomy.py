_UNITY_COPY_SUFFIX = re.compile(r" \(\d+\)$")


def normalize_prefab(name: str) -> str:
    """Strip the " (N)" suffix Unity gives duplicated scene objects.

    A save can store GEAR_Stick (4) for a stick that was placed by hand in the
    level. It is still a GEAR_Stick.
    """
    return _UNITY_COPY_SUFFIX.sub("", name)


def prefab_source(name: str) -> str:
    """Where a prefab comes from.

    Returns "base", "DLC01", "DLC02", "mod:<pack>", "legacy", or "unknown" for a
    name that TAXONOMY_LOOKUP does not have.
    """
    prefab = normalize_prefab(name)
    if prefab in DLC_PREFABS:
        return DLC_PREFABS[prefab]
    if prefab in MOD_PREFABS:
        return "mod:" + MOD_PREFABS[prefab]
    if prefab in LEGACY_PREFABS:
        return "legacy"
    if prefab in TAXONOMY_LOOKUP:
        return "base"
    return "unknown"


def display_name(name: str) -> str:
    """The name the game shows for a prefab, or "" when no source states it."""
    prefab = normalize_prefab(name)
    return (GAME_NAMES.get(prefab) or EDITOR_NAMES.get(prefab) or MOD_NAMES.get(prefab)
            or WIKI_NAMES.get(prefab) or "")


def display_name_source(name: str) -> str:
    """Where display_name() takes a prefab's name from: "game", "editor", "mod", "wiki", or "" for none."""
    prefab = normalize_prefab(name)
    for source, table in (("game", GAME_NAMES), ("editor", EDITOR_NAMES), ("mod", MOD_NAMES),
                          ("wiki", WIKI_NAMES)):
        if prefab in table:
            return source
    return ""
